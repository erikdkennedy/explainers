#!/usr/bin/env node
/*
 * Injects the header splash's animation layer into a raw Figma export.
 *
 *     node tools/qm-splash/animate.mjs [input.svg]
 *
 * The splash is used as a CSS `background-image`, which means the browser loads it in a
 * sandboxed mode: no scripting inside the file, and no way for the page's stylesheet or
 * quantum.js to reach in. So every moving part has to be declarative CSS living inside the
 * SVG itself — including the reduced-motion guard, which cannot be inherited from the site.
 *
 * Run it again after any re-export from Figma. It is idempotent: it strips its own previous
 * output first, matches the curves it animates by their path data rather than by position in
 * the file, and throws if any anchor has gone missing rather than silently shipping a static
 * splash. See README.md.
 */

